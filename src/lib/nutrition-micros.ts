export function microsFor(foodName: string): Micros | null {
  const row = TABLE[foodName];
  return row ? Object.fromEntries(MICRO_KEYS.map((k, i) => [k, row[i]])) : null;
}

/** Scale per-100 g micros to a weight. */
export function scaleMicros(m: Micros | null, grams: number): Micros | null {
  if (!m) return null;
  return Object.fromEntries(Object.entries(m).map(([k, v]) => [k, Math.round((v ?? 0) * grams) / 100])) as Micros;
}

export function sumMicros(list: (Micros | null | undefined)[]): Micros {
  const out: Micros = {};
  for (const m of list) {
    if (!m) continue;
    for (const k of MICRO_KEYS) if (m[k] !== undefined) out[k] = Math.round(((out[k] ?? 0) + (m[k] ?? 0)) * 10) / 10;
  }
  return out;
}

